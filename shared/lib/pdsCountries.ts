/** Real country names (no placeholder or blank slots), for building a <select>. */
export const PDS_COUNTRIES: readonly string[] = PDS_COUNTRY_SLOTS.slice(1).filter((c) => c !== "");

/** 1-based dropdown index of a country in the template's list, or 0 if it isn't in the list. */
export function pdsCountryIndex(country: string | null | undefined): number {
  const wanted = (country || "")
    .replace(/\u00a0/g, " ")
    .trim()
    .toLowerCase();
  if (!wanted) return 0;
  const i = PDS_COUNTRY_SLOTS.findIndex((c) => c !== "" && c.toLowerCase() === wanted);
  return i < 0 ? 0 : i + 1;
}
